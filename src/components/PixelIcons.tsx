const palette: Record<string, string> = {
  "1": "#160f1b",
  "2": "currentColor",
  "3": "#f9dc9b",
  "4": "#76513a",
};
function sprite(name: string) {
  return function Icon({ size = 24, className = "", ...props }: IconProps) {
    return (
      <svg
        {...props}
        width={size}
        height={size}
        viewBox="0 0 16 16"
        shapeRendering="crispEdges"
        className={`pixel-icon ${className}`}
        aria-hidden="true"
      >
        {GLYPHS[name].flatMap((row, y) =>
          [...row].map((v, x) =>
            v !== "0" ? (
              <rect
                key={`${x}-${y}`}
                x={x}
                y={y}
                width="1"
                height="1"
                fill={palette[v]}
              />
            ) : null,
          ),
        )}
      </svg>
    );
  };
}
